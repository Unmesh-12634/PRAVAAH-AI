// Sparklines helper
export const getHazardSparklineData = (snapshots: CycloneSnapshot[]) => ({
  wind: snapshots.map((s) => ({ step: s.step, value: s.windSpeed_kmh, label: `${s.windSpeed_kmh} km/h` })),
  rainfall: snapshots.map((s) => ({ step: s.step, value: s.rainfall_mm, label: `${s.rainfall_mm} mm` })),
  surge: snapshots.map((s) => ({ step: s.step, value: s.surgeValue_m, label: `${s.surgeValue_m}m` })),
  risk: snapshots.map((s, idx) => ({ step: s.step, value: idx === 0 ? 2 : idx === 1 ? 3 : idx === 2 ? 4 : 5, label: s.riskLevel })),
});

export const getExposureSparklineData = (snapshots: CycloneSnapshot[]) => ({
  population: snapshots.map((s) => ({ step: s.step, value: s.exposedPop_raw / 1000000, label: s.exposedPopulation })),
  assets: snapshots.map((s) => ({ step: s.step, value: s.highRiskAssets, label: `${s.highRiskAssets}` })),
  hospitals: snapshots.map((s) => ({ step: s.step, value: s.hospitalsAtRisk, label: `${s.hospitalsAtRisk}` })),
  roads: snapshots.map((s) => ({ step: s.step, value: s.roadsAtRisk, label: `${s.roadsAtRisk} km` })),
});

